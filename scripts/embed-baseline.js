#!/usr/bin/env node
/**
 * Embeds baseline.yaml into src/audit/bundled-baseline.js so the Worker
 * and Node tests share a single source of truth (no hand-copied string).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const yaml = readFileSync(join(root, 'baseline.yaml'), 'utf8');
const out = join(root, 'src/audit/bundled-baseline.js');

const body = `/** Auto-generated by scripts/embed-baseline.js — do not edit by hand. */\n`
  + `export const BUNDLED_BASELINE = ${JSON.stringify(yaml)};\n`;

writeFileSync(out, body);
console.log(`Wrote ${out} (${yaml.length} chars)`);
